const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const dates=fs.readFileSync('colaborador/portal-v2-dates.js','utf8');
const stage4=fs.readFileSync('colaborador/portal-v2-stage4.js','utf8');
const signature=fs.readFileSync('colaborador/portal-v2-signature.js','utf8');
const stage3=fs.readFileSync('colaborador/portal-v2-stage3.js','utf8');
const html=fs.readFileSync('runtime/colaboradores.html','utf8');
const dateTags=[...stage4.matchAll(/type=['"]date['"]/g),...signature.matchAll(/type=['"]date['"]/g)];
assert.equal(dateTags.length,0,'No browser-dependent MM/DD/YYYY inputs in collaborator activity and signature forms');
assert.match(html,/portal-v2-dates\.js\?v=20261112-mx/);
assert.ok(html.indexOf('portal-v2-dates.js')<html.indexOf('portal-v2-stage4.js'));
assert.match(stage4,/key:'firma',short:'Firma'/);
assert.ok(stage4.indexOf("key:'firma'")<stage4.indexOf("key:'alta'"));
assert.match(stage3,/\['Contrato firmado'/);
const dom=new JSDOM('<div id="page-content"></div>',{url:'https://example.test',runScripts:'outside-only'});
const w=dom.window;
w.eval(dates);
const d=w.caV2Dates;
assert.equal(d.toMX('2026-11-12'),'12/11/2026');
assert.equal(d.toMX('2026-11-12T15:30:00Z'),'12/11/2026');
assert.equal(d.toMX('12/11/2026'),'12/11/2026');
assert.equal(d.toISO('12/11/2026'),'2026-11-12');
assert.equal(d.toISO('01/03/2026'),'2026-03-01');
assert.equal(d.toISO('29/02/2024'),'2024-02-29');
assert.equal(d.toISO('29/02/2026'),'');
assert.equal(d.toISO('31/11/2026'),'');
assert.equal(d.toISO('11/12/26'),'');
assert.equal(d.toMX('01112026'),'01/11/2026');
w.state={page:'clientes',bootstrap:{advisor:{name:'ASESOR'},clients:[{id:'c1',name:'CLIENTE DE PRUEBA',serviceId:'retiro_desempleo',stage:'contrato_firmas',registeredAt:'2026-11-12',updatedAt:'2026-11-12T12:00:00Z',progress:{done:{}},appointment:{date:'',time:'',branch:''}}]}};
w.esc=v=>String(v||'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;','\x27':'&#39;'}[c]));
w.navigate=()=>{};
w.refreshDashboardOnly=async()=>{};
w.portalAction=async()=>{throw new Error('Do not call backend in UI test');};
w.toast=()=>{};
w.eval(stage4);
w.eval(signature);
w.navigate('clientes');
const headers=[...w.document.querySelectorAll('.ca-v2-table thead th')].map(x=>x.textContent);
assert.deepEqual(headers.slice(0,3),['Cliente','Firma','Alta']);
assert.equal(w.document.querySelectorAll('.ca-v2-table thead th').length,10);
assert.equal(w.document.querySelectorAll('.ca-v2-table tbody .ca-v2-step').length,9);
w.caV2OpenActivity('c1','firma');
assert.equal(w.document.getElementById('ca-signature-modal').hidden,false);
assert.equal(w.document.getElementById('ca-signature-date').type,'text');
assert.equal(w.document.getElementById('ca-signature-date').getAttribute('placeholder'),'dd/mm/aaaa');
w.caV2CloseSignature();
w.caV2OpenActivity('c1','alta');
const input=w.document.getElementById('ca-v2-date');
assert.equal(input.type,'text');
assert.equal(input.placeholder,'dd/mm/aaaa');
assert.equal(input.value,'12/11/2026');
w.close();
console.log('PASS: Mexican dd/mm/aaaa values, strict date validation, signed-contract first and no native US-style fields.');
