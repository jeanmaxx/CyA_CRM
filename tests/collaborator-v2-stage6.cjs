const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('runtime/colaboradores.html','utf8');
const script=fs.readFileSync('colaborador/portal-v2-stage6.js','utf8');
const css=fs.readFileSync('colaborador/portal-v2-stage6.css','utf8');
const app=fs.readFileSync('colaborador/app.js','utf8');
assert.match(html,/portal-v2-stage6\.js\?v=20261112-next-activity/);
assert.match(html,/portal-v2-stage6\.css\?v=20261112-s6/);
assert.match(css,/\.hero\.ca-home-compact/);
assert.match(app,/fillServices\(\);showPortal\(\);window\.navigate\(state\.page,true\)/);
const dom=new JSDOM('<div id="login-view" hidden></div><main id="page-content"><section class="hero"><h1>Hola</h1></section><section class="kpi-grid"></section><section class="section-card"><div class="section-head"><h3>Prospectos recientes</h3></div><div class="quick-list"></div></section></main>',{url:'https://example.test/',runScripts:'outside-only'});
const w=dom.window;
const client={id:'c1',name:'Cliente Uno',serviceId:'retiro_desempleo',stage:'dado_alta'};
const visited=[];
w.state={page:'inicio',bootstrap:{advisor:{name:'EMMANUEL ÁLVAREZ'},collaborator:{name:'JESSICA'},clients:[client]},prospects:[{id:'p1',name:'Prospecto Uno',internalStatus:'sindos',createdAt:'2026-11-01'}]};
w.esc=v=>String(v||'').replace(/[&<>"']/g,x=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[x]));
w.dateMX=()=> '01/11/2026';
w.navigate=p=>visited.push(p);
w.caV2ActivitySteps=[{key:'alta',title:'Cliente dado de alta'},{key:'cita',title:'Crear cita en AFORE'}];
w.caV2ActivityCompleted=(_c,k)=>k==='alta';
w.caV2OpenActivity=(id,key)=>visited.push(id+':'+key);
w.eval(script);
assert.match(w.document.querySelector('.hero h1').textContent,/Hola, Jessica/);
assert.match(w.document.querySelector('.advisor-pill').textContent,/Emmanuel Álvarez/);
assert.equal(w.document.querySelectorAll('#ca-home-tasks .ca-home-task').length,1);
assert.match(w.document.getElementById('ca-home-tasks').textContent,/Crear cita en AFORE/);
const task=w.document.querySelector('.ca-home-task');
assert.ok(task.querySelector('.ca-home-task-priority'));
assert.equal(task.children[0].querySelector('strong').textContent,'Cliente Uno');
assert.match(task.children[1].textContent,/Crear cita en AFORE/);
assert.equal(task.children[2].textContent,'Revisar');
assert.equal(w.document.querySelector('.quick-stage'),null,'No recent prospects section on home');
assert.equal(w.document.querySelectorAll('#page-content .section-card').length,1);
assert.equal(w.document.querySelector('.kpi-grid').nextElementSibling?.id,'ca-home-tasks');
w.document.querySelector('.ca-home-task button').click();
assert.ok(visited.includes('c1:cita'));
w.navigate('clientes');
assert.ok(visited.includes('clientes'));
w.close();
console.log('PASS: compact welcome, KPIs, no recent prospects, client priorities and accessible navigation.');
