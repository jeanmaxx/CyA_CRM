const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const guide=fs.readFileSync('colaborador/phase4.js','utf8');
const polish=fs.readFileSync('colaborador/portal-v2-polish.css','utf8');
const expediente=fs.readFileSync('colaborador/portal-v2-stage3.js','utf8');
const html=fs.readFileSync('runtime/colaboradores.html','utf8');
assert.doesNotMatch(guide,/sessionStorage|localStorage|portalAction\(|guide_toggle|guide_reset|guideTarget|guideSteps=data/);
assert.doesNotMatch(guide,/caSelectGuideTarget|data-page-clients/);
assert.match(guide,/visibilitychange/);
assert.match(guide,/Reiniciar guía/);
assert.match(polish,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)!important/);
assert.match(polish,/\.ca-v2-table\{width:100%!important;min-width:0!important;table-layout:fixed!important/);
assert.match(polish,/@media\(max-width:979px\)/);
assert.match(html,/portal-v2-polish\.css\?v=20261112-layout/);
assert.match(html,/phase4\.js\?v=20261112-free-guide/);
assert.match(expediente,/<small>Banco<\/small>/);
assert.doesNotMatch(expediente,/<small>Etapa en CRM<\/small>/);
const dom=new JSDOM('<nav><button type="button" data-page="guia"></button></nav><div id="page-title"></div><button id="new-prospect-top"></button><div id="page-content"></div>',{url:'https://example.test',runScripts:'outside-only'});
const w=dom.window;
w.scrollTo=()=>{};
w.state={page:'inicio',bootstrap:{guideContent:[],clients:[{id:'c',name:'PRUEBA'}]},prospects:[{id:'p',name:'DEMO'}]};
w.esc=s=>String(s||'');
w.navigate=page=>{w.state.page=page;};
w.eval(guide);
w.navigate('guia');
assert.equal(w.document.querySelectorAll('.guide-step').length,11);
assert.equal(w.document.querySelectorAll('select').length,0);
assert.equal(w.document.querySelectorAll('button.guide-reset-icon').length,1);
assert.equal(w.document.querySelector('.guide-progress-pill').textContent,'0/11');
w.caToggleGuideStep(1,true);
assert.equal(w.document.querySelector('.guide-progress-pill').textContent,'1/11');
w.navigate('clientes');
w.navigate('guia');
assert.equal(w.document.querySelector('.guide-progress-pill').textContent,'0/11','Checks must reset when leaving guide');
w.caToggleGuideStep(4,true);
w.caResetGuide();
assert.equal(w.document.querySelector('.guide-progress-pill').textContent,'0/11','Reset icon clears checklist');
w.caToggleGuideStep(2,true);
Object.defineProperty(w.document,'hidden',{configurable:true,get:()=>true});
w.document.dispatchEvent(new w.Event('visibilitychange'));
Object.defineProperty(w.document,'hidden',{configurable:true,get:()=>false});
w.document.dispatchEvent(new w.Event('visibilitychange'));
assert.equal(w.document.querySelector('.guide-progress-pill').textContent,'0/11','Switching browser tabs resets guide');
dom.window.close();
console.log('PASS: isolated ephemeral guide, resets, compact CSS dimensions and bank summary.');
