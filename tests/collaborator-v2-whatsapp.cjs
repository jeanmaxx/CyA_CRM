const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('runtime/colaboradores.html','utf8');
const client=fs.readFileSync('colaborador/portal-v2-stage3.js','utf8');
const app=fs.readFileSync('colaborador/app.js','utf8');
const edge=fs.readFileSync('supabase/functions/collaborator-portal/index.ts','utf8');
const source=fs.readFileSync('colaborador/portal-v2-whatsapp.js','utf8');
assert.match(html,/id="ca-wa-prospect"/);
assert.match(html,/portal-v2-whatsapp\.js\?v=20261112-wa/);
assert.match(client,/id="ca-wa-client"/);
assert.match(client,/caV2OpenWhatsApp\?\.\('client',activeClientId\)/);
assert.match(app,/caV2OpenWhatsApp\?\.\('lead',p\.id\)/);
assert.match(edge,/admin\.from\('agenda_events'\)\.upsert/);
assert.match(edge,/onConflict:'organization_id,id'/);
assert.match(edge,/agendaWarning/);
const dom=new JSDOM('<main></main>',{url:'https://example.test/',runScripts:'outside-only'});
const w=dom.window;
const actions=[];
w.state={bootstrap:{collaborator:{name:'JESSICA MENDOZA'},clients:[{id:'c',name:'JUAN CARLOS PÉREZ',phone:'4421234567'}]},prospects:[{id:'p',name:'MARÍA LOZANO',phone:'4423334455'}]};
w.open=(url,target,features)=>{actions.push({url,target,features});return {};};
w.navigator.clipboard={writeText:async()=>{}};
w.eval(source);
w.caV2OpenWhatsApp('client','c');
assert.equal(w.document.getElementById('ca-wa-modal').hidden,false);
assert.match(w.document.getElementById('ca-wa-message').value,/Juan/);
assert.match(w.document.getElementById('ca-wa-message').value,/Jessica/);
assert.equal(actions.length,0,'No automatic WhatsApp sending');
w.document.getElementById('ca-wa-send').click();
assert.equal(actions.length,1);
assert.match(actions[0].url,/^https:\/\/wa\.me\/524421234567\?text=/);
assert.match(decodeURIComponent(actions[0].url),/Juan/);
w.caV2WhatsAppClose();
w.caV2OpenWhatsApp('lead','p');
assert.match(w.document.getElementById('ca-wa-message').value,/María/);
assert.equal(actions.length,1,'No automatic send on prospect open');
w.document.getElementById('ca-wa-template').value='documentos';
w.document.getElementById('ca-wa-template').dispatchEvent(new w.Event('change'));
assert.match(w.document.getElementById('ca-wa-message').value,/INE/);
w.close();
console.log('PASS: WhatsApp buttons, personalized templates, manual-only sending and appointment sync contract.');
